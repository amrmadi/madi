/**
 * The application shell: header, navigation, and the content area.
 *
 * Navigation is the primary way a caregiver moves around, so it uses large
 * tap targets and a clear active state. On narrow screens the links wrap onto
 * their own row rather than collapsing into a hamburger menu — a menu costs an
 * extra tap and hides the destination, which is exactly wrong for this
 * audience.
 */

import { Link, NavLink, Outlet, useNavigate } from 'react-router-dom'

import { useAuth } from '../auth/AuthContext'

/** A single navigation link with a visible active state. */
function NavItem({ to, children }: { to: string; children: React.ReactNode }) {
  return (
    <NavLink
      to={to}
      className={({ isActive }) =>
        [
          'rounded-lg px-4 py-2 text-base font-semibold transition-colors min-h-touch inline-flex items-center',
          isActive
            ? 'bg-brand-600 text-white'
            : 'text-slate-700 hover:bg-slate-200',
        ].join(' ')
      }
    >
      {children}
    </NavLink>
  )
}

export function AppLayout() {
  const { user, signOut } = useAuth()
  const navigate = useNavigate()

  function handleSignOut() {
    signOut()
    navigate('/login', { replace: true })
  }

  return (
    <div className="min-h-screen bg-slate-50">
      {/* The skip link is the first focusable element: keyboard users can jump
          straight past the navigation to the content. */}
      <a
        href="#main-content"
        className="sr-only focus:not-sr-only focus:absolute focus:left-4 focus:top-4 focus:z-50 focus:rounded-lg focus:bg-brand-600 focus:px-4 focus:py-2 focus:text-white"
      >
        Skip to main content
      </a>

      <header className="border-b border-slate-200 bg-white">
        <div className="mx-auto max-w-6xl px-4 py-4">
          <div className="flex flex-wrap items-center justify-between gap-4">
            <Link to="/dashboard" className="flex items-center gap-3">
              <span className="text-3xl" aria-hidden="true">
                🏡
              </span>
              <span className="text-2xl font-bold text-brand-800">ElderLife AI</span>
            </Link>

            {user && (
              <div className="flex items-center gap-3">
                <div className="text-right">
                  <p className="text-base font-semibold text-slate-800">
                    {user.display_name}
                  </p>
                  <p className="text-sm text-slate-500">{user.email}</p>
                </div>
                <span className="rounded-full border border-brand-200 bg-brand-50 px-3 py-1 text-sm font-semibold text-brand-800">
                  {user.role}
                </span>
                <button type="button" className="btn-secondary" onClick={handleSignOut}>
                  Sign out
                </button>
              </div>
            )}
          </div>

          {user && (
            <nav aria-label="Main navigation" className="mt-4 flex flex-wrap gap-2">
              <NavItem to="/dashboard">Dashboard</NavItem>
              <NavItem to="/residents">Residents</NavItem>
              <NavItem to="/alerts">Alerts</NavItem>
            </nav>
          )}
        </div>
      </header>

      <main id="main-content" className="mx-auto max-w-6xl px-4 py-8">
        <Outlet />
      </main>

      <footer className="border-t border-slate-200 bg-white py-6">
        <div className="mx-auto max-w-6xl px-4 text-base text-slate-500">
          <p>
            ElderLife AI — graduation project. Data shown here is entered by
            caregivers or generated by the demo seed script; activity marked
            &ldquo;simulated&rdquo; is not a real sensor reading.
          </p>
        </div>
      </footer>
    </div>
  )
}
